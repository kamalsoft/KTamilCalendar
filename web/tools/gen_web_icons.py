#!/usr/bin/env python3
"""Generates web/src/main/resources/web/engine/icons.js: the month-grid symbols, as in the Android app.

Source of truth: the vector drawables (app/src/main/res/drawable/badge_*.xml, rel_*.xml), mapped to
DayTag / Religion by Badges.kt. Run after changing an icon or its mapping:  python3 web/tools/gen_web_icons.py
"""
import json
import pathlib
import re
import xml.etree.ElementTree as ET

ROOT = pathlib.Path(__file__).resolve().parents[2]
SHARED = ROOT / "shared/src/main/java/com/kamalsoft/tamilcalendar/tv"
APP = ROOT / "app/src/main/java/com/kamalsoft/tamilcalendar/tv"
DRAWABLE = ROOT / "app/src/main/res/drawable"
OUT = ROOT / "web/src/main/resources/web/engine/icons.js"
ANDROID = "{http://schemas.android.com/apk/res/android}"


def enum_entries(text, name):
    """[(NAME, en)] in declaration order for `enum class <name>(...) { ... }`."""
    body = re.search(rf"enum class {name}\b[^{{]*\{{(.*?)\n\}}", text, re.S).group(1)
    return [(m.group(1), m.group(3)) for m in re.finditer(r'^\s+([A-Z_]+)\("([^"]*)", "([^"]*)"', body, re.M)]


def svg_of(path):
    """Converts an Android vector drawable into an SVG string (paths, fills and strokes only)."""
    root = ET.parse(path).getroot()
    w, h = root.get(ANDROID + "viewportWidth"), root.get(ANDROID + "viewportHeight")
    parts = []
    for p in root.iter("path"):
        attrs = {
            "d": p.get(ANDROID + "pathData"),
            "fill": p.get(ANDROID + "fillColor", "none"),
            "stroke": p.get(ANDROID + "strokeColor"),
            "stroke-width": p.get(ANDROID + "strokeWidth"),
            "stroke-linecap": p.get(ANDROID + "strokeLineCap"),
            "stroke-linejoin": p.get(ANDROID + "strokeLineJoin"),
        }
        parts.append("<path " + " ".join(f'{k}="{v}"' for k, v in attrs.items() if v is not None) + "/>")
    return f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {w} {h}">' + "".join(parts) + "</svg>"


def main():
    tamil_day = (SHARED / "domain/model/TamilDayData.kt").read_text(encoding="utf-8")
    badges = (APP / "ui/components/Badges.kt").read_text(encoding="utf-8")
    day_tags = enum_entries(tamil_day, "DayTag")
    religions = enum_entries(tamil_day, "Religion")
    # Badges.kt maps each DayTag / Religion to its drawable; Hindu has no symbol.
    mapping = dict(re.findall(r"(?:DayTag|Religion)\.(\w+) -> R\.drawable\.(\w+)", badges))
    labels = dict(day_tags + religions)

    icons = {}
    for name, drawable in mapping.items():
        icons[name] = {"en": labels[name], "svg": svg_of(DRAWABLE / f"{drawable}.xml")}
    # Every tag and every non-Hindu faith needs a symbol; GOVT_HOLIDAY is shown as the holiday red, not as an icon.
    missing = [n for n, _ in day_tags if n not in icons and n != "GOVT_HOLIDAY"] + [n for n, _ in religions if n not in icons and n != "HINDU"]
    assert not missing, f"no icon for {missing}"

    out = [
        "// Generated by web/tools/gen_web_icons.py from the Android vector drawables. Do not edit by hand.",
        f"export const TAG_ORDER = {json.dumps([n for n, _ in day_tags])};",
        f"export const RELIGION_ORDER = {json.dumps([n for n, _ in religions])};",
        "export const ICON = {",
    ]
    for name, item in icons.items():
        out.append(f"  {name}: {json.dumps(item, ensure_ascii=False)},")
    out += ["};", ""]
    OUT.write_text("\n".join(out), encoding="utf-8")
    print(f"wrote {len(icons)} icons to {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
