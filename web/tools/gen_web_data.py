#!/usr/bin/env python3
"""Generates web/src/main/resources/web/engine/content.js from the Android app's Kotlin sources.

Run after changing names, texts or themes in the app:  python3 web/tools/gen_web_data.py
The Kotlin files are the single source of truth; the output is committed so the site needs no build step.
"""
import json
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parents[2]
SHARED = ROOT / "shared/src/main/java/com/kamalsoft/tamilcalendar/tv"
APP = ROOT / "app/src/main/java/com/kamalsoft/tamilcalendar/tv"
OUT = ROOT / "web/src/main/resources/web/engine/content.js"


def block(text, start_marker, end_marker):
    i = text.index(start_marker)
    j = text.index(end_marker, i)
    return text[i:j]


def pairs(text):
    return [list(m) for m in re.findall(r'"([^"]+)" to "([^"]+)"', text)]


def gen_names():
    src = (SHARED / "domain/model/TamilNames.kt").read_text()
    out = {}
    for name in ["months", "years", "tithis", "nakshatras", "rasis", "yogas", "weekdays"]:
        out[name] = pairs(block(src, f"val {name} = listOf(", "\n    )"))
    return out


def gen_gochara():
    src = (APP / "domain/content/Gochara.kt").read_text()
    lines = lambda name: [list(m) for m in re.findall(r'Line\("([^"]*)", "([^"]*)"\)', block(src, f"val {name} = listOf(", "\n    )"))]
    rahu = re.findall(r'val (RAHU_GOOD|RAHU_BAD) = Line\("([^"]*)", "([^"]*)"\)', src)
    return {
        "sun": lines("SUN"), "jupiter": lines("JUPITER"), "saturn": lines("SATURN"),
        "rahuGood": [rahu[0][1], rahu[0][2]], "rahuBad": [rahu[1][1], rahu[1][2]],
    }


def gen_slokas():
    src = (APP / "domain/content/Slokas.kt").read_text()
    out = {}
    for m in re.finditer(r'val (\w+) = Sloka\(\n(.*?)\n    \)', src, re.S):
        body = m.group(2)
        strings = re.findall(r'"((?:[^"\\]|\\.)*)"', body)
        deity = re.search(r'Deity\.(\w+)|null', body)
        out[m.group(1)] = {
            "id": strings[0], "titleTa": strings[1], "titleEn": strings[2],
            "deity": deity.group(1) if deity and deity.group(1) else None,
            "textTa": strings[3], "transliteration": strings[4], "meaningEn": strings[5], "source": strings[6],
        }
    order = re.search(r'val ALL = listOf\((.*?)\)', src).group(1)
    out["_order"] = [s.strip() for s in order.split(",")]
    return out


def gen_rasi_messages():
    src = (APP / "domain/usecase/RasiPalanCalculator.kt").read_text()
    found = re.findall(r'RasiOutlook\.(\w+) to \("([^"]*)" to "([^"]*)"\)', src)
    return [{"outlook": o, "ta": t, "en": e} for o, t, e in found]


def gen_themes():
    src = (APP / "ui/theme/Theme.kt").read_text()
    body = block(src, "enum class AppTheme(", "    companion object")
    themes = []
    for chunk in re.split(r'\n    (?=[A-Z_]+\(\n)', body)[1:]:
        name = re.match(r'([A-Z_]+)\(', chunk).group(1)
        names = re.search(r'"([^"]*)",\s*"([^"]*)"', chunk)
        colors = dict((k, "#" + v[2:]) for k, v in re.findall(r'(\w+) = Color\(0x([0-9A-Fa-f]{8})\)', chunk))
        themes.append({
            "id": name, "ta": names.group(1), "en": names.group(2), "colors": colors,
            "isLight": "isLight = true" in chunk, "focusRing": "focusRing = true" in chunk,
        })
    return themes


ENUMS = {
    "Religion": "domain/model/TamilDayData.kt", "Deity": "domain/model/TamilDayData.kt",
    "DayTag": "domain/model/TamilDayData.kt", "TimingType": "domain/model/TamilDayData.kt",
    "Gowri": "domain/model/TamilDayData.kt", "HolidayRegion": "domain/model/TamilDayData.kt",
    "Paksha": "domain/model/TamilDayData.kt", "RasiOutlook": "domain/model/TamilDayData.kt",
}


def gen_enums():
    """Each entry: [NAME, ta, en, extra] where extra is the isGood flag (Gowri) or the deity (DayTag)."""
    out = {}
    for enum, rel in ENUMS.items():
        src = (SHARED / rel).read_text()
        body = block(src, f"enum class {enum}(", "\n}")
        entries = []
        for m in re.finditer(r'^\s+([A-Z_]+)\((.*?)\)[,;]?\s*$', body, re.M):
            args = m.group(2)
            strs = re.findall(r'"([^"]*)"', args)
            extra = None
            if "isGood" in enum or re.search(r'(true|false)\s*$', args.strip()):
                extra = args.strip().endswith("true")
            dm = re.search(r'Deity\.(\w+)', args)
            if dm:
                extra = dm.group(1)
            entries.append([m.group(1), strs[0], strs[1], extra])
        out[enum] = entries
    return out


def main():
    content = {
        "names": gen_names(),
        "gochara": gen_gochara(),
        "slokas": gen_slokas(),
        "rasiMessages": gen_rasi_messages(),
        "themes": gen_themes(),
        "enums": gen_enums(),
    }
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(
        "// GENERATED by web/tools/gen_web_data.py from the Android app's Kotlin sources. Do not edit by hand.\n"
        "export const CONTENT = " + json.dumps(content, ensure_ascii=False, indent=1) + ";\n"
    )
    print(f"wrote {OUT.relative_to(ROOT)}: {len(content['themes'])} themes, {len(content['slokas']) - 1} slokas, "
          f"{len(content['names']['nakshatras'])} nakshatras, {len(content['rasiMessages'])} rasi messages, "
          f"enums {{{', '.join(f'{k}:{len(v)}' for k, v in content['enums'].items())}}}")


if __name__ == "__main__":
    main()
